#| ---------------------- | --------------------------------------- | --------------------------------- |
#| Architecture           | Encoder                                 | Decoder                           |
#| Main idea              | Understand text                         | Generate text                     |
#| Attention              | Bidirectional                           | Causal/masked                     |
#| Typical use            | Classification, representations, QA     | Text generation, chat, completion |
#| Future tokens visible? | In encoder context, yes                 | No                                |
